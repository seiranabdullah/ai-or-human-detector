# ## 6. Model training and comparison
# The data is split into **80% training** and **20% testing** (stratified, so both parts keep the same class ratio).
#
# We compare four models:
#
# | # | Model | Input |
# |---|---|---|
# | 1 | Random Forest | 8 writing-style features only |
# | 2 | Multinomial Naive Bayes | word counts (CountVectorizer) |
# | 3 | Logistic Regression | TF-IDF of words and word pairs |
# | 4 | Linear SVM | TF-IDF of words and word pairs |

# %%
X_train, X_test, y_train, y_test = train_test_split(
    df["text"], df["generated"], test_size=0.2, random_state=RANDOM_STATE, stratify=df["generated"])
print("Training essays:", len(X_train), "  Test essays:", len(X_test))

# %%
models = {
    "Random Forest (style features)": make_pipeline(
        StandardScaler(), RandomForestClassifier(n_estimators=200, random_state=RANDOM_STATE, n_jobs=-1)),
    "Naive Bayes (word counts)": make_pipeline(
        CountVectorizer(ngram_range=(1, 2), min_df=3, max_features=50000), MultinomialNB()),
    "Logistic Regression (TF-IDF)": make_pipeline(
        TfidfVectorizer(ngram_range=(1, 2), min_df=3, max_features=50000, sublinear_tf=True),
        LogisticRegression(max_iter=2000, C=5)),
    "Linear SVM (TF-IDF)": make_pipeline(
        TfidfVectorizer(ngram_range=(1, 2), min_df=3, max_features=50000, sublinear_tf=True),
        LinearSVC(C=0.5)),
}

style_train = features_frame(X_train)
style_test = features_frame(X_test)

results, fitted = [], {}
for name, model in models.items():
    use_style = name.startswith("Random Forest")
    xtr, xte = (style_train, style_test) if use_style else (X_train, X_test)
    t0 = time.time()
    model.fit(xtr, y_train)
    train_time = time.time() - t0
    pred = model.predict(xte)
    fitted[name] = model
    results.append({
        "model": name,
        "accuracy": metrics.accuracy_score(y_test, pred),
        "precision": metrics.precision_score(y_test, pred),
        "recall": metrics.recall_score(y_test, pred),
        "f1": metrics.f1_score(y_test, pred),
        "train_time_s": train_time,
    })
    print(f"{name:34s} F1 = {results[-1]['f1']:.4f}   ({train_time:.1f} s)")

results_df = pd.DataFrame(results).set_index("model").round(4)
