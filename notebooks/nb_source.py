# - EDA shows clear style differences: AI essays are shorter, more uniform, use longer words and vary sentence length less.
# - TF-IDF + Logistic Regression reaches an F1-score above 0.99 on the test set and in 5-fold cross-validation.
# - The model needs enough text: below about 100 words the quality drops.
# - **Main limitation:** on a different type of text (scientific abstracts) the model fails. AI detection should be used as **support for a human decision, never as proof**.
